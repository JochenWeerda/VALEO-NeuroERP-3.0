"""Generate the two immutable public schemas without protected network reads."""
import argparse
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.core.public_auth_screen_definitions import build_public_auth_screen
OUT = ROOT / "packages/frontend-web/src/masks/public-auth.generated.ts"


def render():
    return "// Generated by scripts/generate_public_auth_screens.py\nimport type { ScreenDefinition } from '@/components/mask-builder/schema'\n" + "\n".join(
        f"export const {name} = {json.dumps(build_public_auth_screen(sid), ensure_ascii=False, indent=2)} satisfies ScreenDefinition\n"
        for name, sid in [("loginScreen", "auth/login"), ("callbackScreen", "auth/callback")])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        raise SystemExit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == expected else 1)
    OUT.write_text(expected, encoding="utf-8")
